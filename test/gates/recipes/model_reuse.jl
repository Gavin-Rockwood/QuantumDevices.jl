@testset "cached model gates and reference offsets" begin
    d = QuantumDevice(:cached_gate)
    q = add_component!(d,make_flux_tunable_transmon(:q,.25,18;d=.1,dimension=7))
    flux = q.variables["flux"]
    recipe = Recipe(d,[q];states=Dict(q=>0:2))
    pulse = Pulse(GaussianZero(.3;duration=2);duration=2,amplitude=.04,delay=1,offset=flux)
    gate = GateRecipe(recipe;controls=[Control(:flux,flux,pulse)])
    @test isequal(gate.controls[1].pulse.offset,flux)
    @test_throws ArgumentError pulse(0)
    @test_throws ArgumentError Pulse(Constant(;duration=1);duration=1,offset=flux+1)
    @test_throws ArgumentError Pulse(Constant(;duration=1);duration=1,amplitude=flux)
    @test_throws ArgumentError Pulse(Constant(;duration=flux);duration=flux)
    @test isequal(calibration_parameters(pulse)["offset"][2],flux)
    for value in (.12,.23)
        model = build(d,recipe;parameters=Dict(flux=>value))
        prepared = build(d,gate;parameters=Dict(flux=>value))
        actual = make_hamiltonian(model,gate)
        expected = make_hamiltonian(prepared)
        for t in (0.,1.,1.3,2.,3.,4.)
            @test actual(nothing,t) ≈ expected(nothing,t)
        end
        @test check_endpoints(model,gate;atol=1e-14)
        @test check_endpoints(prepared;atol=1e-14)
        @test isequal(gate.controls[1].pulse.offset,flux)
        @test make_hamiltonian(model,draft(prepared.recipe))(nothing,1.5) ≈ actual(nothing,1.5)
        equivalent = Recipe(d,[q];states=Dict(q=>0:2),dressing_options=(thread_count=2,))
        equivalent_gate = GateRecipe(equivalent;controls=gate.controls)
        @test make_hamiltonian(model,equivalent_gate)(nothing,1.5) ≈ actual(nothing,1.5)
        @test make_hamiltonian(model,QuantumGate(:working,gate))(nothing,1.5) ≈ actual(nothing,1.5)
        wrong = Recipe(d,[q];states=Dict(q=>0:2),parameters=Dict(flux=>.45))
        @test_throws ArgumentError make_hamiltonian(model,GateRecipe(wrong;controls=gate.controls))
        @test_throws ArgumentError make_hamiltonian(model,GateRecipe(:named;controls=gate.controls))
        @test make_hamiltonian(model,GateRecipe(recipe;duration=1)) ≈ make_hamiltonian(model)
        n = recipe.inputs.q.operators.charge
        drive = Symbolics.variable(:cached_drive)
        term = Interaction(:drive,drive*n;parameters=Dict(drive=>0.))
        driven = GateRecipe(recipe;terms=[term],controls=[Control(:drive,drive,Pulse(Constant(;duration=1);duration=1,amplitude=.02))])
        @test make_hamiltonian(model,driven)(nothing,.5) ≈ make_hamiltonian(build(d,driven;parameters=Dict(flux=>value)))(nothing,.5)
        square = Interaction(:square,drive*n^3;parameters=Dict(drive=>.03))
        squaregate = GateRecipe(recipe;terms=[square],duration=1)
        @test_throws ArgumentError make_hamiltonian(model,squaregate)
        projected = build(d,squaregate;parameters=Dict(flux=>value))
        @test make_hamiltonian(projected.model,squaregate) ≈ make_hamiltonian(projected)
        conflict = Interaction(:conflict,flux*n;parameters=Dict(flux=>.9))
        @test_throws ArgumentError make_hamiltonian(model,GateRecipe(recipe;terms=[conflict],duration=1))
        missing = Symbolics.variable(:missing_offset)
        bad = GateRecipe(recipe;controls=[Control(:flux,flux,Pulse(Constant(;duration=1);duration=1,offset=missing))])
        @test_throws ArgumentError make_hamiltonian(model,bad)
        @test_throws ArgumentError build(d,bad;parameters=Dict(flux=>value))
        sequence = PulseSequence(Pulse(Constant(;duration=1);duration=1,offset=flux,amplitude=0),
            Pulse(Constant(;duration=1);duration=1,delay=2,offset=flux,amplitude=0);delay=1,offset=flux)
        seqgate = GateRecipe(recipe;controls=[Control(:flux,flux,sequence)])
        seq = make_hamiltonian(model,seqgate)
        for t in (0.,1.,2.,3.,4.,5.,6.)
            @test seq(nothing,t) ≈ make_hamiltonian(model)
        end
        @test check_endpoints(model,seqgate)
        @test_throws ArgumentError CalibrationProblem(prepared,["flux/offset"],Matrix{ComplexF64}(I,3,3))
        problem = CalibrationProblem(prepared,["flux/amplitude"],Matrix{ComplexF64}(I,3,3))
        candidate = QuantumDevices._update_gate_pulses(prepared.recipe,["flux/amplitude"=>.02])
        @test isequal(candidate.controls[1].pulse.offset,flux)
        @test make_hamiltonian(model,candidate)(nothing,0) ≈ make_hamiltonian(model)
        mktempdir() do directory
            path = joinpath(directory,"pulse.jld2")
            save_pulse(path,sequence)
            restored = load_pulse(path)
            @test isequal(restored.offset,flux)
            @test isequal(restored.pulses[1].offset,flux)
            contextpath = joinpath(directory,"gate.jld2")
            QuantumDevices.JLD2.jldsave(contextpath;prepared)
            copy = QuantumDevices.JLD2.load(contextpath,"prepared")
            @test isequal(copy.recipe.controls[1].pulse.offset,flux)
            @test make_hamiltonian(copy)(nothing,1.5) ≈ actual(nothing,1.5)
            @test make_hamiltonian(copy.model,copy.recipe)(nothing,1.5) ≈ actual(nothing,1.5)
        end
    end
    # An explicit downstream assignment masks a different upstream declaration.
    leaf = Leaf(component=:q,parameters=Dict(flux=>.1))
    parent = Recipe(d,[q];inputs=(upstream=leaf,),states=Dict(:upstream=>0:2),parameters=Dict(flux=>.2))
    model = build(d,parent)
    compatible = draft(parent)
    compatible.inputs.upstream.recipe.parameters[flux] = .3
    @test make_hamiltonian(model,GateRecipe(compatible;duration=1)) ≈ make_hamiltonian(model)
    empty!(compatible.parameters)
    @test_throws ArgumentError make_hamiltonian(model,GateRecipe(compatible;duration=1))
    different = Recipe(d,[q];states=Dict(q=>[0,2]))
    @test_throws ArgumentError make_hamiltonian(model,GateRecipe(different;duration=1))
    # Baselines can name another model parameter; runtime replacement never feeds them.
    model = build(d,recipe;parameters=Dict(flux=>.2))
    other = q.variables["EC"]
    cross = GateRecipe(recipe;controls=[Control(:flux,flux,Pulse(Constant(;duration=1);duration=1,amplitude=0,offset=other))])
    @test make_hamiltonian(model,cross)(nothing,.5) ≈ make_hamiltonian(model,[flux])(Dict(flux=>(t->model.parameters[other])),.5)
    complexmodel = build(d,recipe;parameters=Dict(flux=>.2+0im))
    modulated = GateRecipe(recipe;controls=[Control(:flux,flux,Pulse(Constant(;duration=1),1.;duration=1,offset=flux))])
    @test_throws ArgumentError make_hamiltonian(complexmodel,modulated)
end

@testset "reuse never invokes generators and preserves adjoints" begin
    device = QuantumDevice(:no_rebuild)
    q = add_component!(device,make_qubit(:q))
    calls = Ref(0)
    generator = OperatorGenerator(n -> begin
        calls[] += 1
        QT.sigmam()
    end,2)
    recipe = Leaf(component=:q,generators=Dict(OperatorRef(:q,:x)=>generator))
    amplitude = Symbolics.variable(:reuse_complex_drive)
    term = Interaction(:complex,amplitude*op(:q,:x)+adjoint(amplitude*op(:q,:x));parameters=Dict(amplitude=>0.))
    pulse = Pulse(Constant(;duration=1);duration=1,amplitude=.03im)
    gate = GateRecipe(recipe;terms=[term],controls=[Control(:drive,amplitude,pulse)])
    prepared = build(device,gate)
    count = calls[]
    actual = make_hamiltonian(prepared.model,gate)
    @test calls[] == count
    @test actual(nothing,.5) ≈ make_hamiltonian(prepared)(nothing,.5)
    @test calls[] == count
    missing = Interaction(:missing,amplitude*op(:q,:x)*adjoint(op(:q,:x));parameters=Dict(amplitude=>0.))
    @test_throws ArgumentError make_hamiltonian(prepared.model,GateRecipe(recipe;terms=[missing],duration=1))
    incomplete = Interaction(:incomplete,amplitude*op(:q,:x))
    @test_throws ArgumentError make_hamiltonian(prepared.model,GateRecipe(recipe;terms=[incomplete],controls=[Control(:drive,amplitude,pulse)]))
    @test calls[] == count
end

@testset "reuse compares scoped interactions and upstream choices" begin
    d = QuantumDevice(:reuse_tree)
    a = add_component!(d,make_qubit(:a))
    b = add_component!(d,make_qubit(:b))
    interaction = Interaction(:coupling,.01*op(:a,:x)*op(:b,:x))
    recipe = Recipe(d,[a,b];interactions=[interaction])
    model = build(d,recipe)
    equivalent = Recipe(d,[a,b];interactions=[interaction])
    @test make_hamiltonian(model,GateRecipe(equivalent;duration=1)) ≈ make_hamiltonian(model)
    changed = Recipe(d,[a,b];interactions=[Interaction(:coupling,.02*op(:a,:x)*op(:b,:x))])
    @test_throws ArgumentError make_hamiltonian(model,GateRecipe(changed;duration=1))
    altered = Recipe(d,[a,b];interactions=[interaction],dressing_options=(nsteps=3,))
    @test_throws ArgumentError make_hamiltonian(model,GateRecipe(altered;duration=1))
    scoped = Interaction(:extra,.01*equivalent.inputs.a.operators.x*equivalent.inputs.b.operators.x)
    with_extra = GateRecipe(equivalent;terms=[scoped],duration=1)
    @test make_hamiltonian(model,with_extra) ≈ make_hamiltonian(build(d,with_extra))
    foreign = Interaction(:foreign,.01*recipe.inputs.a.operators.x)
    @test_throws ArgumentError make_hamiltonian(model,GateRecipe(equivalent;terms=[foreign],duration=1))
    upstream = Recipe(d,[a,b];inputs=(pair=recipe,),states=Dict(:pair=>[0,1]))
    nestedmodel = build(d,upstream)
    @test make_hamiltonian(nestedmodel,GateRecipe(draft(upstream);duration=1)) ≈ make_hamiltonian(nestedmodel)
    different_upstream = Recipe(d,[a,b];inputs=(pair=changed,),states=Dict(:pair=>[0,1]))
    @test_throws ArgumentError make_hamiltonian(nestedmodel,GateRecipe(different_upstream;duration=1))
    other_order = Recipe(d,[b,a];interactions=[interaction])
    @test_throws ArgumentError make_hamiltonian(model,GateRecipe(other_order;duration=1))
end
